const fs = require('fs');
const path = require('path');
const root = 'd:/Projects/ws-blog-static';

function readJsonFile(filePath) {
  let raw = fs.readFileSync(filePath, 'utf8');
  // Strip UTF-8 BOM if present
  if (raw.charCodeAt(0) === 0xFEFF) raw = raw.slice(1);
  return JSON.parse(raw);
}

const articles   = readJsonFile(path.join(root, 'data/articles.json'));
const categories = readJsonFile(path.join(root, 'data/categories.json'));
const authors    = readJsonFile(path.join(root, 'data/authors.json'));
const featured   = readJsonFile(path.join(root, 'data/featured.json'));
const trendingData = readJsonFile(path.join(root, 'data/trending.json'));

const trendingIds = trendingData.trending || [];
const featuredIds = featured.featured || [];

const helpers = `
/* ---- Helper functions ---- */
function getArticles() { return ARTICLES_DATA; }
function getCategories() { return CATEGORIES_DATA; }
function getAuthors() { return AUTHORS_DATA; }
function getArticleById(id) { return ARTICLES_DATA.find(a => a.id === id || a.slug === id) || null; }
function getCategoryById(id) { return CATEGORIES_DATA.find(c => c.id === id) || null; }
function getAuthorById(id) { return AUTHORS_DATA.find(a => a.id === id) || null; }
function getArticlesByCategory(catId) { return ARTICLES_DATA.filter(a => a.category === catId); }
function getTrending(limit) {
  const n = limit || 10;
  const result = [];
  for (const id of TRENDING_IDS) { const a = getArticleById(id); if (a) result.push(a); if (result.length >= n) break; }
  if (result.length < n) {
    const sorted = [...ARTICLES_DATA].sort((a,b) => new Date(b.publishedDate) - new Date(a.publishedDate));
    for (const a of sorted) { if (!result.find(r => r.id === a.id)) { result.push(a); if (result.length >= n) break; } }
  }
  return result;
}
function getFeatured() {
  const result = [];
  for (const id of FEATURED_IDS) { const a = getArticleById(id); if (a) result.push(a); }
  return result.length ? result : ARTICLES_DATA.filter(a => a.featured).slice(0, 5);
}
function getLatest(n) { return [...ARTICLES_DATA].sort((a,b) => new Date(b.publishedDate) - new Date(a.publishedDate)).slice(0, n || ARTICLES_DATA.length); }
function searchArticles(q) {
  if (!q || !q.trim()) return [];
  const query = q.toLowerCase().trim();
  return ARTICLES_DATA.filter(a =>
    (a.title && a.title.toLowerCase().includes(query)) ||
    (a.excerpt && a.excerpt.toLowerCase().includes(query)) ||
    (a.category && a.category.toLowerCase().includes(query)) ||
    (a.tags && a.tags.some(t => t.toLowerCase().includes(query)))
  );
}
function getCategoryForArticle(article) {
  if (!article) return null;
  return getCategoryById(article.category) || { id: article.category, name: article.category, color: '#194cff', bgColor: '#e8edff', icon: '' };
}
function getAuthorForArticle(article) {
  if (!article) return null;
  return getAuthorById(article.author) || { id: article.author, name: article.author, role: 'Writer', avatar: 'assets/images/authors/default.svg', bio: '' };
}`;

const out = `/* ============================================================
   data.js — Inline data + helpers. UTF-8. Generated by Node.js.
   ============================================================ */
const ARTICLES_DATA = ${JSON.stringify(articles, null, 2)};
const CATEGORIES_DATA = ${JSON.stringify(categories, null, 2)};
const AUTHORS_DATA = ${JSON.stringify(authors, null, 2)};
const TRENDING_IDS = ${JSON.stringify(trendingIds)};
const FEATURED_IDS = ${JSON.stringify(featuredIds)};
${helpers}
`;

fs.writeFileSync(path.join(root, 'assets/js/data.js'), out, 'utf8');
const verify = fs.readFileSync(path.join(root, 'assets/js/data.js'), 'utf8');
console.log('Size:', Math.round(out.length/1024) + 'KB');
console.log('Emoji check (has emoji icon chars):', verify.includes('\uD83D\uDCC8') ? 'OK emoji found' : ('char check: ' + [...verify.matchAll(/[\u{1F300}-\u{1F9FF}]/gu)].length + ' emoji chars'));
console.log('No BOM corruption:', !verify.includes('\xEF\xBB\xBF'));
console.log('Categories present:', verify.includes('"digital-marketing"'));
console.log('Article count:', (verify.match(/"id":\s*"what-is/g) || []).length, 'key articles found');